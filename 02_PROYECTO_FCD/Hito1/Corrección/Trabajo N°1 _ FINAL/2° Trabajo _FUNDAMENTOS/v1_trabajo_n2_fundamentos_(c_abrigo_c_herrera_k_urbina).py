"""
### 12.3.1. Optimización de Hiperparámetros para Random Forest (GridSearchCV)

Vamos a utilizar `GridSearchCV` para encontrar la mejor combinación de hiperparámetros para el modelo `RandomForestRegressor`. Esto nos permitirá mejorar el rendimiento del modelo más allá de la configuración inicial."""

from sklearn.model_selection import GridSearchCV

# Definimos el pipeline para Random Forest
rf_pipeline = Pipeline(
    steps=[
        ('prep', preprocesador),
        ('reg', RandomForestRegressor(random_state=RANDOM_STATE))
    ]
)

# Definimos el rango de hiperparámetros a buscar
param_grid_rf = {
    'reg__n_estimators': [100, 200, 300], # Número de árboles en el bosque
    'reg__max_depth': [10, 15, 20],      # Profundidad máxima de los árboles
    'reg__min_samples_leaf': [5, 10, 20] # Número mínimo de muestras requeridas para estar en un nodo hoja
}

print("Iniciando GridSearchCV para RandomForestRegressor...")

# Configuramos GridSearchCV
# 'neg_mean_absolute_error' es la métrica que queremos minimizar
grid_search_rf = GridSearchCV(
    rf_pipeline,
    param_grid_rf,
    cv=cv, # Usamos la misma validación cruzada definida anteriormente
    scoring='neg_mean_absolute_error', # Se optimiza MAE (negativo para GridSearchCV)
    n_jobs=-1,
    verbose=2 # Mostrar el progreso
)

# Ejecutamos la búsqueda en el conjunto de entrenamiento
grid_search_rf.fit(X_train, y_train)

print("\nGridSearchCV completado.")
print(f"Mejores hiperparámetros encontrados: {grid_search_rf.best_params_}")
print(f"Mejor MAE (negativo) en CV: {grid_search_rf.best_score_:.2f}")
print(f"Mejor MAE (positivo) en CV: {-grid_search_rf.best_score_:.2f} AUD")

"""### 12.3.2. Evaluación del Modelo Random Forest Optimizado

Una vez que `GridSearchCV` ha encontrado los mejores hiperparámetros, evaluamos el rendimiento del modelo optimizado en el conjunto de prueba de 2017.
"""

import pandas as pd

# Obtenemos el mejor modelo
best_rf_model = grid_search_rf.best_estimator_

# Realizamos predicciones en el conjunto de prueba (2017)
y_pred_best_rf = best_rf_model.predict(X_test)

# Calculamos las métricas de evaluación
r2_test_optimized = r2_score(y_test, y_pred_best_rf)
mae_test_optimized = mean_absolute_error(y_test, y_pred_best_rf)
rmse_test_optimized = np.sqrt(mean_squared_error(y_test, y_pred_best_rf))

print("\n--- Métricas del Random Forest Optimizado (Test 2017) ---")
print(f"R² Test (2017): {r2_test_optimized:.4f}")
print(f"MAE Test ($): {mae_test_optimized:.2f}")
print(f"RMSE Test ($): {rmse_test_optimized:.2f}")

# Calculamos métricas para el conjunto de entrenamiento para la tabla
y_pred_train_optimized = best_rf_model.predict(X_train)
r2_train_optimized = r2_score(y_train, y_pred_train_optimized)

# Calculamos el R² de CV para el mejor modelo optimizado
# Usamos cross_val_score directamente sobre el best_rf_model para obtener el R2 de CV
scores_cv_optimized = cross_val_score(
    best_rf_model, X_train, y_train, cv=cv, scoring='r2', n_jobs=-1
)
cv_r2_optimized = scores_cv_optimized.mean()

# Añadimos este resultado a la tabla comparativa
resultados_lista.append({
    'Modelo': 'Random Forest Optimizado',
    'R² CV (Train 16)': round(cv_r2_optimized, 4),
    'R² Train': round(r2_train_optimized, 4),
    'R² Test (2017)': round(r2_test_optimized, 4),
    'MAE Test ($)': round(mae_test_optimized, 2),
    'RMSE Test ($)': round(rmse_test_optimized, 2),
    'Δ R² (Train-Test)': round(r2_train_optimized - r2_test_optimized, 4),
})

tabla_resultados_updated = pd.DataFrame(resultados_lista)
print('\n================ TABLA COMPARATIVA DE DESEMPEÑO ACTUALIZADA ================')
