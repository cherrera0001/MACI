# 4. PREPARACIÓN DE DATOS Y PARTICIÓN TEMPORAL ESTRICTA

# ¿Qué vamos a hacer?
# Definir la matriz de predictores $X$ y el vector objetivo $y$, separando estrictamente
# por el año cronológico: 2016 para Entrenamiento y 2017 para Evaluación de Prueba (Test).

# ¿Por qué lo hacemos?
# Para cumplir el mandato de la Tarea T2 y prevenir el *data leakage*. Si se aplicara una partición aleatoria,
# transacciones del futuro contaminarían el entrenamiento.

# 4.1. Selección de Variables Predictoras Justificadas
variables_numericas = [
    'Habitaciones',
    'Baños',
    'Automóviles',
    'Distancia',
    'Tamaño_Tierra',
    'Latitud',
    'Longitud',
    'Cantidad_Propiedades',
]

variables_categoricas = [
    'Tipo',
    'Método',
    'Región',
]

features_seleccionadas = variables_numericas + variables_categoricas

# Partición temporal estricta
train_mask = df['Year'] == 2016
test_mask = df['Year'] == 2017

X_train = df.loc[train_mask, features_seleccionadas]
y_train = df.loc[train_mask, 'Precio']

X_test = df.loc[test_mask, features_seleccionadas]
y_test = df.loc[test_mask, 'Precio']

print(f'Muestra de Entrenamiento (2016): {X_train.shape[0]:,} observaciones.')
print(f'Muestra de Evaluación Test (2017): {X_test.shape[0]:,} observaciones.')


# 5. PIPELINE DE PREPROCESAMIENTO Y CONTROL DE DATA LEAKAGE

# ¿Qué vamos a hacer?
# Construir un `ColumnTransformer` que encapsule:
# - Imputación numérica con mediana calculada exclusivamente en Train.
# - Escalado estándar (`StandardScaler`) para algoritmos sensibles a distancias.
# - Codificación One-Hot para variables categóricas con control de categorías no vistas (`handle_unknown='ignore'`).

# ¿Por qué lo hacemos?
# Evita la filtración de información de Test hacia Train. Cualquier parámetro estadístico
# (media, mediana, desviación) debe ser aprendido únicamente del conjunto de 2016.


# 5.1. Construcción del Preprocesador
preprocesador = ColumnTransformer(
    transformers=[
        (
            'num',
            Pipeline(
                steps=[
                    ('imputer', SimpleImputer(strategy='median')),
                    ('scaler', StandardScaler()),
                ]
            ),
            variables_numericas,
        ),
        (
            'cat',
            Pipeline(
                steps=[
                    (
                        'imputer',
                        SimpleImputer(strategy='constant', fill_value='missing'),
                    ),
                    (
                        'encoder',
                        OneHotEncoder(
                            handle_unknown='ignore', sparse_output=False
                        ),
                    ),
                ]
            ),
            variables_categoricas,
        ),
    ]
)


# 6. DEFINICIÓN DEL BASELINE Y MODELOS CANDIDATOS

# ¿Qué vamos a hacer?
# Definir y evaluar cuatro enfoques:
# 1. Baseline:** `DummyRegressor(strategy='median')`.
# 2. Regresión Lineal Múltiple:** Modelo paramétrico interpretable de referencia.
# 3. Árbol de Decisión:** Modelo no lineal de particionamiento recursivo.
# 4. Random Forest Regressor:** Ensamble de embolsamiento (*bagging*) con reducción de varianza.
# 5. Gradient Boosting Regressor:** Ensamble de potenciación (*boosting*) que optimiza residuales de forma secuencial.

# ¿Por qué lo hacemos?
# Para determinar si la complejidad de modelos no lineales justifica su costo computacional
# frente a modelos lineales y si superan verdaderamente a la heurística base.


# 6.1. Diccionario de Modelos Integrados en Pipelines
modelos = {
    'Baseline (Mediana 2016)': DummyRegressor(strategy='median'),
    'Regresión Lineal': Pipeline(
        steps=[('prep', preprocesador), ('reg', LinearRegression())]
    ),
    'Árbol de Decisión': Pipeline(
        steps=[
            ('prep', preprocesador),
            (
                'reg',
                DecisionTreeRegressor(
                    max_depth=10, min_samples_leaf=15, random_state=RANDOM_STATE
                ),
            ),
        ]
    ),
    'Random Forest': Pipeline(
        steps=[
            ('prep', preprocesador),
            (
                'reg',
                RandomForestRegressor(
                    n_estimators=150,
                    max_depth=16,
                    min_samples_leaf=5,
                    n_jobs=-1,
                    random_state=RANDOM_STATE,
                ),
            ),
        ]
    ),
    'Gradient Boosting': Pipeline(
        steps=[
            ('prep', preprocesador),
            (
                'reg',
                GradientBoostingRegressor(
                    n_estimators=150,
                    max_depth=6,
                    learning_rate=0.08,
                    random_state=RANDOM_STATE,
                ),
            ),
        ]
    ),
}


# 7. VALIDACIÓN CRUZADA Y EVALUACIÓN FINAL EN TEST (2017)

# ¿Qué vamos a hacer?
# 1. Ejecutar validación cruzada ($K=5$) sobre el set de Train 2016 para auditar estabilidad interna.
# 2. Ajustar los modelos con la totalidad de 2016 y predecir el set de Test 2017.
# 3. Calcular métricas clave: MAE, RMSE y $R^2$.


# 7.1. Bucle de Entrenamiento y Evaluación Sistemática
cv = KFold(n_splits=5, shuffle=True, random_state=RANDOM_STATE)
resultados_lista = []

print('Ejecutando validación cruzada y evaluación en Test 2017...\n')

for nombre, modelo in modelos.items():
  # Validación cruzada sobre Train 2016 usando R2 y MAE negativo
  if nombre == 'Baseline (Mediana 2016)':
    cv_r2_mean = 0.0
    modelo.fit(X_train[['Habitaciones']], y_train)
    y_pred_train = modelo.predict(X_train[['Habitaciones']])
    y_pred_test = modelo.predict(X_test[['Habitaciones']])
  else:
    scores_cv = cross_val_score(
        modelo, X_train, y_train, cv=cv, scoring='r2', n_jobs=-1
    )
    cv_r2_mean = scores_cv.mean()

    # Ajuste en Train 2016 completo
    modelo.fit(X_train, y_train)
    y_pred_train = modelo.predict(X_train)
    y_pred_test = modelo.predict(X_test)

  # Métricas de Entrenamiento (2016)
  r2_train = r2_score(y_train, y_pred_train)
  mae_train = mean_absolute_error(y_train, y_pred_train)
  rmse_train = np.sqrt(mean_squared_error(y_train, y_pred_train))

  # Métricas de Evaluación Fuera de Muestra (Test 2017)
  r2_test = r2_score(y_test, y_pred_test)
  mae_test = mean_absolute_error(y_test, y_pred_test)
  rmse_test = np.sqrt(mean_squared_error(y_test, y_pred_test))

  resultados_lista.append({
      'Modelo': nombre,
      'R² CV (Train 16)': round(cv_r2_mean, 4),
      'R² Train': round(r2_train, 4),
      'R² Test (2017)': round(r2_test, 4),
      'MAE Test ($)': round(mae_test, 2),
      'RMSE Test ($)': round(rmse_test, 2),
      'Δ R² (Train-Test)': round(r2_train - r2_test, 4),
  })

# 7.2. Tabla Comparativa Final
tabla_resultados = pd.DataFrame(resultados_lista)
print('================ TABLA COMPARATIVA DE DESEMPEÑO ================')
print(tabla_resultados.to_string(index=False))


